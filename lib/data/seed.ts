/**
 * Dados de demonstração da fase de protótipo. Na fase 2 este arquivo vira o
 * script de seed do banco (Supabase/Postgres) e some do runtime.
 */

function portfolio(seed: number, count = 6): PortfolioItem[] {
  const aspects: PortfolioItem["aspect"][] = ["wide", "tall", "square"];
  return Array.from({ length: count }, (_, i) => {
    const n = (seed * 977 + i * 341) % 9000 + 1000;
    return {
      id: `p${seed}-${i}`,
      label: `IMG_${n}.RAW`,
      tone: (seed + i) % 6,
      aspect: aspects[(seed + i * 2) % 3],
    };
  });
}

